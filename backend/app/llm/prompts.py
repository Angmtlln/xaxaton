def build_block_user_message(block: str, title: str, company: Dict[str, Any],
                             facts: List[Dict[str, Any]], missing: List[str],
                             coverage: Dict[str, Any]) -> str:
    """Вход блочного агента: только факты своего блока, без сырого JSON."""
    payload = {
        "компания": company,
        "блок": {"key": block, "title": title},
        "полнота_данных": {
            "заполнено_блоков": coverage.get("filled_blocks"),
            "всего_блоков": coverage.get("total_blocks"),
            "пустые_блоки": coverage.get("empty_blocks"),
        },
        "чего_нет_в_блоке": missing,
        "факты": facts,
    }
    return (
        "Проанализируй блок «%s» по фактам ниже и верни JSON по схеме.\n\n%s"
        % (title, json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
    )


def build_summary_user_message(company: Dict[str, Any], blocks: List[Dict[str, Any]],
                               key_facts: List[Dict[str, Any]],
                               coverage: Dict[str, Any]) -> str:
    payload = {
        "компания": company,
        "оценки_банка": {
            "riskLevel": company.get("risk_level"),
            "zskRiskLevel": company.get("zsk_risk_level"),
        },
        "полнота_данных": coverage,
        "блочные_резюме": blocks,
        "ключевые_факты": key_facts,
    }
    return (
        "Собери итоговый ответ по контрагенту и верни JSON по схеме.\n\n%s"
        % json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    )


def block_system_prompt(block: str) -> str:
    return "%s\n\n%s\n\n%s" % (BLOCK_SYSTEM_PROMPTS[block], COMMON_RULES, OUTPUT_SCHEMA)
